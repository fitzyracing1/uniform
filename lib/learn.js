// `uniform learn`: read someone's own code and write down how they actually write it.
// Everything here is local file reads. Nothing is uploaded anywhere.
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const { codeFiles, isIgnored, readIgnore } = require('./files');

const CODE = /\.(ts|tsx|mts|cts|js|jsx|cjs|mjs)$/;
const TEST = /(^|\/)(test|tests|__tests__)\/|\.(test|spec)\.[a-z]+$/;
const WHY =
  /, so\b|\b(because|so that|so we|so it|otherwise|since|why|workaround|can't|cannot|don't|doesn't|won't|avoid|instead|on purpose|careful|note|hack|must|has to|have to|needs? to|keep|would|only|never|always|else)\b/i;
const WHAT =
  /^(increment|decrement|return|returns|get|gets|set|sets|create|creates|loop|iterate|check if|call|calls|initiali[sz]e|define|declare|import|export|add|adds|update|updates)\b/i;
const MARKER = '<!-- generated by uniform learn -->';

function caseOf(name) {
  const bare = name.replace(/^_+|_+$/g, '');
  if (!bare || /^[a-z][a-z0-9]*$/.test(bare)) return 'lower';
  if (/^[A-Z][A-Z0-9_]*$/.test(bare) && bare.length > 1) return 'UPPER_CASE';
  if (/^[a-z][a-z0-9]*(_[a-z0-9]+)+$/.test(bare)) return 'snake_case';
  if (/^[a-z][a-zA-Z0-9]*$/.test(bare)) return 'camelCase';
  if (/^[A-Z][a-zA-Z0-9]*$/.test(bare)) return 'PascalCase';
  return 'other';
}

function percentile(values, p) {
  if (!values.length) return 0;
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.min(sorted.length - 1, Math.ceil((p / 100) * sorted.length) - 1)];
}

function ratio(part, whole) {
  return whole ? Math.round((part / whole) * 1000) / 1000 : 0;
}

function emptyStats() {
  return {
    files: 0,
    codeLines: 0,
    lineWidths: [],
    names: { value: [], type: [] },
    functionLines: [],
    depths: [],
    comments: { line: 0, block: 0, jsdoc: 0, why: 0, what: 0, other: 0 },
    quotes: { single: 0, double: 0 },
    semis: { with: 0, without: 0 },
    indents: { two: 0, four: 0, tab: 0 },
    trailingCommas: { with: 0, without: 0 },
    imports: { esm: 0, require: 0, nodePrefixed: 0, nodeBare: 0, typeOnly: 0 },
    errors: { catches: 0, emptyCatches: 0, commentedEmptyCatches: 0, throws: 0, errorClasses: 0 },
  };
}

const BUILTINS = new Set([
  'fs',
  'path',
  'os',
  'child_process',
  'readline',
  'util',
  'crypto',
  'url',
  'http',
  'https',
  'zlib',
  'events',
  'stream',
  'assert',
  'net',
  'buffer',
]);

function countModule(stats, spec) {
  if (spec.startsWith('node:')) stats.imports.nodePrefixed++;
  else if (BUILTINS.has(spec.split('/')[0])) stats.imports.nodeBare++;
}

function recordName(stats, node, kind) {
  if (node && ts.isIdentifier(node)) stats.names[kind].push(node.text);
}

function walkAst(stats, source, isTest) {
  const visit = (node, depth) => {
    let next = depth;
    if (ts.isVariableDeclaration(node) || ts.isParameter(node)) recordName(stats, node.name, 'value');
    else if (ts.isFunctionDeclaration(node) || ts.isMethodDeclaration(node)) recordName(stats, node.name, 'value');
    else if (
      ts.isClassDeclaration(node) ||
      ts.isInterfaceDeclaration(node) ||
      ts.isTypeAliasDeclaration(node) ||
      ts.isEnumDeclaration(node)
    ) {
      recordName(stats, node.name, 'type');
      if (ts.isClassDeclaration(node) && node.heritageClauses?.some((h) => /\bError\b/.test(h.getText(source))))
        stats.errors.errorClasses++;
    }
    if (ts.isFunctionLike(node) && node.body && !isTest) {
      const start = source.getLineAndCharacterOfPosition(node.getStart(source)).line;
      const end = source.getLineAndCharacterOfPosition(node.end).line;
      stats.functionLines.push(end - start + 1);
      next = 0;
    }
    const elseIf = ts.isIfStatement(node) && ts.isIfStatement(node.parent) && node.parent.elseStatement === node;
    if (elseIf) next = depth;
    else if (
      ts.isIfStatement(node) ||
      ts.isForStatement(node) ||
      ts.isForOfStatement(node) ||
      ts.isForInStatement(node) ||
      ts.isWhileStatement(node) ||
      ts.isDoStatement(node) ||
      ts.isSwitchStatement(node) ||
      ts.isTryStatement(node)
    ) {
      next = depth + 1;
      if (!isTest) stats.depths.push(next);
    }
    countSyntax(stats, node, source);
    ts.forEachChild(node, (child) => visit(child, next));
  };
  visit(source, 0);
}

function countSyntax(stats, node, source) {
  if (ts.isStringLiteral(node)) {
    const quote = source.text[node.getStart(source)];
    if (quote === "'") stats.quotes.single++;
    else if (quote === '"' && !ts.isImportDeclaration(node.parent) && !ts.isJsxAttribute(node.parent))
      stats.quotes.double++;
  }
  if (ts.isImportDeclaration(node)) {
    stats.imports.esm++;
    if (ts.isStringLiteral(node.moduleSpecifier)) countModule(stats, node.moduleSpecifier.text);
    const clause = node.importClause;
    if (clause && (clause.isTypeOnly || clause.namedBindings?.elements?.some((e) => e.isTypeOnly)))
      stats.imports.typeOnly++;
  }
  if (
    ts.isCallExpression(node) &&
    ts.isIdentifier(node.expression) &&
    node.expression.text === 'require' &&
    node.arguments[0] &&
    ts.isStringLiteral(node.arguments[0])
  ) {
    stats.imports.require++;
    countModule(stats, node.arguments[0].text);
  }
  if (ts.isCatchClause(node)) {
    stats.errors.catches++;
    if (node.block.statements.length === 0) {
      stats.errors.emptyCatches++;
      if (/\/[/*]/.test(node.block.getText(source))) stats.errors.commentedEmptyCatches++;
    }
  }
  if (ts.isThrowStatement(node)) stats.errors.throws++;
  if (ts.isExpressionStatement(node) || ts.isVariableStatement(node) || ts.isReturnStatement(node)) {
    if (node.getText(source).trimEnd().endsWith(';')) stats.semis.with++;
    else stats.semis.without++;
  }
}

function classifyComment(text) {
  const t = text.trim();
  if (WHY.test(t)) return 'why';
  if (WHAT.test(t) || t.split(/\s+/).length <= 3) return 'what';
  return 'other';
}

function scanText(stats, text) {
  let previous = 0;
  for (const line of text.split(/\r?\n/)) {
    if (!line.trim()) continue;
    stats.codeLines++;
    stats.lineWidths.push(line.length);
    const indent = /^\s*/.exec(line)[0];
    if (indent.startsWith('\t')) stats.indents.tab++;
    // the step between one level and the next is the indent, not the absolute width
    const step = indent.length - previous;
    if (step === 2) stats.indents.two++;
    else if (step === 4) stats.indents.four++;
    previous = indent.length;
  }
  stats.trailingCommas.with += text.match(/,\s*\n\s*[)\]}]/g)?.length ?? 0;
  // `;` and `}` before a closer end a statement or block, so they say nothing about trailing commas
  stats.trailingCommas.without += text.match(/[^,;{}\s[(]\s*\n\s*[)\]}]/g)?.length ?? 0;
}

function scanComments(stats, source) {
  const seen = new Set();
  const visit = (node) => {
    for (const range of ts.getLeadingCommentRanges(source.text, node.getFullStart()) ?? []) {
      if (seen.has(range.pos)) continue;
      seen.add(range.pos);
      const raw = source.text.slice(range.pos, range.end);
      if (raw.startsWith('/**')) stats.comments.jsdoc++;
      else if (raw.startsWith('//')) {
        if (/^\/\/\s*(eslint|@ts-|prettier|#region|#endregion)/.test(raw) || raw.startsWith('#!')) continue;
        stats.comments.line++;
        stats.comments[classifyComment(raw.slice(2))]++;
      } else {
        stats.comments.block++;
        stats.comments[classifyComment(raw.slice(2, -2))]++;
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
}

function collect(dir) {
  const root = path.resolve(dir);
  const ignore = readIgnore(root);
  const stats = emptyStats();
  for (const file of codeFiles(root).filter((f) => CODE.test(f) && !isIgnored(f, ignore))) {
    const text = fs.readFileSync(path.join(root, file), 'utf8');
    const kind = /\.tsx$/.test(file)
      ? ts.ScriptKind.TSX
      : /\.jsx$/.test(file)
        ? ts.ScriptKind.JSX
        : /\.[cm]?js$/.test(file)
          ? ts.ScriptKind.JS
          : ts.ScriptKind.TS;
    const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, kind);
    stats.files++;
    scanText(stats, text);
    walkAst(stats, source, TEST.test(file));
    scanComments(stats, source);
  }
  return stats;
}

function namingSummary(names) {
  const counts = {};
  for (const n of names) counts[caseOf(n)] = (counts[caseOf(n)] ?? 0) + 1;
  const lengths = names.map((n) => n.length);
  return {
    count: names.length,
    cases: Object.fromEntries(
      Object.entries(counts)
        .sort((a, b) => b[1] - a[1])
        .map(([k, v]) => [k, ratio(v, names.length)]),
    ),
    medianLength: percentile(lengths, 50),
    shortShare: ratio(names.filter((n) => n.length <= 2).length, names.length),
  };
}

module.exports = { collect, namingSummary, percentile, ratio, caseOf, classifyComment, MARKER };
